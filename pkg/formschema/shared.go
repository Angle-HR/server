// Job statuses. Hiring owns the job lifecycle; applications only needs the names, so they live here.
const (
	StatusDraft           = "draft"
	StatusPendingApproval = "pending_approval"
	StatusPublished       = "published"
	StatusPaused          = "paused"
	StatusClosed          = "closed"
	StatusArchived        = "archived"
	StatusExpired         = "expired"
)

// DefaultRetentionMonths is the retention period of a new job.
const DefaultRetentionMonths = 6

var uuidRE = regexp.MustCompile(`^[0-9a-fA-F]{8}-[0-9a-fA-F]{4}-[0-9a-fA-F]{4}-[0-9a-fA-F]{4}-[0-9a-fA-F]{12}$`)

// IsUUID reports whether s looks like a UUID.
func IsUUID(s string) bool { return uuidRE.MatchString(s) }

// State is what a candidate may do with a job right now.
type State string

// Job states as a candidate sees them.
const (
	StateOpen   State = "open"   // published and before the closing date: applications are accepted
	StatePaused State = "paused" // visible, but not accepting applications for now
	StateClosed State = "closed" // closed or expired: the page says so and search engines are told to drop it
)

// StateOf derives the candidate-facing state. The closing date is the last day to apply, so a published job
// stays open through it (UTC). The hourly expiry task catches up later; this makes the page correct before it
// runs. The second result is false for statuses that are not public (draft, pending approval) and for archived
// jobs, which the caller reports as not found or gone.
func StateOf(status, closingDate string, now time.Time) (State, bool) {
	switch status {
	case StatusPublished:
		if closingDate != "" && closingDate < now.UTC().Format("2006-01-02") {
			return StateClosed, true
		}
		return StateOpen, true
	case StatusPaused:
		return StatePaused, true
	case StatusClosed, StatusExpired:
		return StateClosed, true
	}
	return "", false
}

// NoticeVersion identifies the wording of the applicant privacy notice an application acknowledged. The text is
// generated by hiring's public package and is a draft until counsel signs it off.
const NoticeVersion = "2026-10-draft"

// ShareChannel is one channel of the Share Kit. Each channel's job link carries ?src=<key>, so an application can
// record which link brought the candidate.
type ShareChannel struct{ Key, Label string }

// ShareChannels fixes the order and labels of the Share Kit channels.
var ShareChannels = []ShareChannel{
	{"whatsapp", "WhatsApp"}, {"x", "X"}, {"facebook", "Facebook"}, {"linkedin", "LinkedIn"},
	{"telegram", "Telegram"}, {"email", "Email"},
}

// ValidSource reports whether src is a share channel the kit issues (or "direct"), so a stored source is always
// one of a small known set instead of free text from the internet.
func ValidSource(src string) bool {
	if src == "direct" {
		return true
	}
	for _, c := range ShareChannels {
		if c.Key == src {
			return true
		}
	}
	return false
}
